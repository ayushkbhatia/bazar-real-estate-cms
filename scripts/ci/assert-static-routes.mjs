#!/usr/bin/env node
/**
 * G-1 — routes that were prerendered must stay prerendered, at the same
 * revalidate interval.
 *
 * The failure this exists to catch: under the `[locale]` segment, a page that
 * forgets `setRequestLocale(locale)` silently opts into dynamic rendering. It
 * still renders correctly, so nothing looks wrong — the `revalidate` export is
 * just quietly discarded and the route drops out of the CDN. There are 38
 * `revalidate` exports in this repo. The first symptom is a Vercel bill weeks
 * later, and this project has already paid for this exact failure once (see
 * the docblock in lib/preferences/provider.tsx).
 *
 * Reads `.next/prerender-manifest.json` rather than scraping the build's route
 * table: it is a stable machine-readable artifact, and it carries the
 * revalidate seconds, which is the thing actually at risk.
 *
 * Keyed by `srcRoute` (the route pattern, `/areas/[slug]`) rather than by
 * concrete URL, because CI builds against LIVE PRODUCTION Supabase — an editor
 * publishing one area would otherwise churn the baseline with no commit behind
 * it.
 *
 * Force-dynamic routes never appear in the manifest, so they never enter the
 * baseline and need no exclusion list. A route moving from static to dynamic
 * therefore shows up as a deletion, which is exactly the signal we want.
 *
 *   node scripts/ci/assert-static-routes.mjs --write-baseline   # once, on main
 *   node scripts/ci/assert-static-routes.mjs                    # in CI
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const MANIFEST = path.join(REPO_ROOT, ".next", "prerender-manifest.json");
const BASELINE = path.join(REPO_ROOT, "scripts", "ci", "route-render-baseline.json");

/** srcRoute -> { revalidate } for everything the build prerendered. */
function readPrerenderedRoutes() {
  if (!existsSync(MANIFEST)) {
    console.error(
      `No ${path.relative(REPO_ROOT, MANIFEST)}.\nRun \`npm run build\` first — this reads the build output.`,
    );
    process.exit(2);
  }

  const manifest = JSON.parse(readFileSync(MANIFEST, "utf8"));
  const bySrc = new Map();

  for (const [url, entry] of Object.entries(manifest.routes ?? {})) {
    const src = entry.srcRoute ?? url;
    if (!bySrc.has(src)) bySrc.set(src, new Set());
    bySrc.get(src).add(entry.initialRevalidateSeconds ?? false);
  }

  const out = {};
  for (const [src, revalidates] of [...bySrc.entries()].sort()) {
    const values = [...revalidates].sort();
    // Concrete pages under one pattern should agree. If they ever don't, record
    // all of them so the diff is legible rather than order-dependent.
    out[src] = { revalidate: values.length === 1 ? values[0] : values };
  }
  return out;
}

const current = readPrerenderedRoutes();

if (process.argv.includes("--write-baseline")) {
  writeFileSync(
    BASELINE,
    `${JSON.stringify(
      {
        $comment:
          "Generated by scripts/ci/assert-static-routes.mjs. srcRoute -> revalidate seconds (false = fully static, no ISR). Regenerate only when a render-mode change is intended, and say why in the PR.",
        routes: current,
      },
      null,
      2,
    )}\n`,
  );
  console.log(
    `Wrote baseline: ${Object.keys(current).length} prerendered routes -> ${path.relative(REPO_ROOT, BASELINE)}`,
  );
  process.exit(0);
}

if (!existsSync(BASELINE)) {
  console.error(
    `No baseline at ${path.relative(REPO_ROOT, BASELINE)}.\nGenerate it with: node scripts/ci/assert-static-routes.mjs --write-baseline`,
  );
  process.exit(2);
}

const baseline = JSON.parse(readFileSync(BASELINE, "utf8")).routes ?? {};

const wentDynamic = [];
const revalidateChanged = [];

for (const [route, expected] of Object.entries(baseline)) {
  const actual = current[route];
  if (!actual) {
    wentDynamic.push(route);
    continue;
  }
  const a = JSON.stringify(actual.revalidate);
  const b = JSON.stringify(expected.revalidate);
  if (a !== b) revalidateChanged.push(`${route}: ${b} -> ${a}`);
}

const added = Object.keys(current).filter((r) => !(r in baseline));

if (added.length) {
  console.log(`New prerendered routes (fine, additive):\n  ${added.join("\n  ")}\n`);
}

if (!wentDynamic.length && !revalidateChanged.length) {
  console.log(
    `OK — all ${Object.keys(baseline).length} baseline routes still prerender at their expected interval.`,
  );
  process.exit(0);
}

if (wentDynamic.length) {
  console.error(
    `These routes were prerendered and are now rendered on demand:\n  ${wentDynamic.join("\n  ")}\n\n` +
      `Each one has silently lost its CDN caching. Under [locale] the usual cause ` +
      `is a missing setRequestLocale(locale) in the page or one of its layouts.\n`,
  );
}

if (revalidateChanged.length) {
  console.error(
    `These routes changed revalidate interval:\n  ${revalidateChanged.join("\n  ")}\n`,
  );
}

console.error(
  `If a change is intentional, regenerate with --write-baseline and say why in the PR.`,
);
process.exit(1);
