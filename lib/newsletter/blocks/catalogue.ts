const BY_TYPE = new Map(BLOCKS.map((b) => [b.type, b]));

export function blockDef(type: string): BlockDef | undefined {
  return BY_TYPE.get(type);
}

/** Every field a translatable text lives in, item fields included: what the Arabic edition must fill. */
export function isTranslatable(f: FieldDef): boolean {
  return (f.kind === "text" || f.kind === "textarea") && f.translatable !== false;
}
